    sGameNow.animId = (uint16_t)animId;
    sGameNow.animKind = (uint8_t)animKind;
    sGameNow.battle = (uint8_t)battle;
    sGameNow.sprites = sprites > 255 ? 255 : (uint8_t)sprites;
