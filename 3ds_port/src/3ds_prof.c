/*
 * Frame profiler (compat/port_prof.h). Sections add their ticks to the frame
 * being made; at present the frame is reported and cleared. A frame that took
 * longer than the display allows is logged whole, section by section, with
 * the screen it was on, and every few seconds the averages are logged: which
 * part of the engine a hitch came from is then in the SD log.
 *
 * Every frame is also one fixed-size record in perf.bin (3ds_log.c), with
 * what the frame was, how it was drawn and where its time went; and frames
 * are gathered into segments - one screen in one mode - whose percentiles,
 * missed VBlanks and 3D losses are logged when the segment ends (PERF lines).
 * scripts/perf_report.py reads both. The boot log says which executable made
 * them (CtrProf_LogIdentity): the baseline of phase F0.
 */
