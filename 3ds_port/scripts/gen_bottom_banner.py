#!/usr/bin/env python3
"""
The bottom screen's banner (assets/artwork/banner.png, the port's own art, the
HOME Menu banner): shown while the game starts and under the screens that give
the bottom screen nothing (the title, the intro, a cutscene).

Written as src/3ds_bottom_banner.h: one RGB565 value a pixel, already laid
over black (the screens it is drawn on are black), 0 where the art is clear.

    python scripts/gen_bottom_banner.py
"""
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.dirname(HERE)
SRC = os.path.join(PORT, "assets", "artwork", "banner.png")
OUT = os.path.join(PORT, "src", "3ds_bottom_banner.h")


def main():
    im = Image.open(SRC).convert("RGBA")
    w, h = im.size
    values = []
    for r, g, b, a in im.getdata():
        r, g, b = (r * a // 255, g * a // 255, b * a // 255)
        values.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    lines = [
        "/* Generated by scripts/gen_bottom_banner.py from assets/artwork/banner.png. Do not edit. */",
        "#ifndef CTR_BOTTOM_BANNER_H",
        "#define CTR_BOTTOM_BANNER_H",
        "#include <stdint.h>",
        "#define BOTTOM_BANNER_W %d" % w,
        "#define BOTTOM_BANNER_H %d" % h,
        "static const uint16_t kBottomBanner[BOTTOM_BANNER_W * BOTTOM_BANNER_H] = {",
    ]
    for i in range(0, len(values), 16):
        lines.append("    " + ",".join("0x%04x" % v for v in values[i:i + 16]) + ",")
    lines += ["};", "#endif", ""]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
