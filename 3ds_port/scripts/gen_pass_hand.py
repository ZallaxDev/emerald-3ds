#!/usr/bin/env python3
"""Draws the Frontier Pass's pointing hand for the top screen.

The pass on the top screen (src/3ds_bottom_pass.inc) has its own cursor,
drawn at the screen's resolution in the bottom screen's colours instead of
the game's 16x16 hand made bigger. It is made here from a few round shapes
(a pointing finger, the palm, three folded fingers, the thumb and an emerald
cuff), each pixel sampled 8x8 times for smooth edges, with a dark outline and
a soft shadow, and written to src/3ds_pass_hand.h as alpha and RGB565 per
pixel. It points left; its tip is PASS_HAND_TIP_X, PASS_HAND_TIP_Y.

Run it again after changing a shape: python3 scripts/gen_pass_hand.py
"""
import math
import os

PORT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(PORT, "src", "3ds_pass_hand.h")

# The shapes are drawn on a 34x30 grid and shown at SCALE of it.
SCALE = 0.8
W, H = 28, 24
SS = 8
OUTLINE = 1.5

INK = (22, 28, 38)
GLOVE = (255, 255, 255)
GLOVE_SHADE = (214, 222, 230)
CUFF = (88, 192, 128)
CUFF_SHADE = (56, 150, 96)
SHADOW = (0, 0, 0)
SHADOW_ALPHA = 0.30
SHADOW_OFFSET = (1.5, 2.0)


def capsule(px, py, ax, ay, bx, by, r):
    dx, dy = bx - ax, by - ay
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy)) - r


def rounded_box(px, py, x0, y0, x1, y1, r):
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    hx, hy = (x1 - x0) / 2 - r, (y1 - y0) / 2 - r
    qx, qy = abs(px - cx) - hx, abs(py - cy) - hy
    return math.hypot(max(qx, 0), max(qy, 0)) + min(max(qx, qy), 0) - r


# The tip of the pointing finger.
TIP = (1.5, 11.0)


def finger(px, py):
    return capsule(px, py, TIP[0] + 3.2, TIP[1], 17.0, 11.5, 3.2)


def folded(px, py):
    return [
        capsule(px, py, 13.0, 17.0, 19.0, 17.0, 2.6),
        capsule(px, py, 13.8, 21.6, 19.0, 21.6, 2.4),
        capsule(px, py, 14.8, 25.8, 19.0, 25.8, 2.2),
    ]


def palm(px, py):
    return rounded_box(px, py, 14.5, 7.5, 27.0, 28.0, 4.5)


def thumb(px, py):
    return capsule(px, py, 15.5, 8.2, 21.5, 5.0, 2.6)


def cuff(px, py):
    return rounded_box(px, py, 25.0, 6.5, 32.5, 29.0, 2.0)


def glove(px, py):
    return min(finger(px, py), min(folded(px, py)), palm(px, py), thumb(px, py))


def shape(px, py):
    """The colour and coverage of one sample, None outside."""
    c = cuff(px, py)
    g = glove(px, py)
    d = min(c, g)
    if d > 0:
        return None
    if d > -OUTLINE:
        return INK
    if c <= -OUTLINE and c <= g:
        # The cuff, darker on its lower half.
        return CUFF if py < 17.5 else CUFF_SHADE
    # The lines between the folded fingers and along the pointing finger.
    for f in folded(px, py):
        if abs(f) < 0.55 and px < 21.5:
            return INK
    if abs(finger(px, py)) < 0.55 and 13.0 < px < 17.5:
        return INK
    if abs(thumb(px, py)) < 0.55 and px > 16.5:
        return INK
    # Shade along the lower edge of each part.
    return GLOVE_SHADE if g > -OUTLINE - 1.2 and py > 12.0 else GLOVE


def render():
    pixels = []
    for y in range(H):
        for x in range(W):
            r = g = b = a = 0.0
            shadow = 0.0
            for sy in range(SS):
                for sx in range(SS):
                    px, py = (x + (sx + 0.5) / SS) / SCALE, (y + (sy + 0.5) / SS) / SCALE
                    c = shape(px, py)
                    if c is not None:
                        r += c[0]
                        g += c[1]
                        b += c[2]
                        a += 1
                    elif min(cuff(px - SHADOW_OFFSET[0], py - SHADOW_OFFSET[1]),
                             glove(px - SHADOW_OFFSET[0], py - SHADOW_OFFSET[1])) <= 0:
                        shadow += 1
            n = SS * SS
            cover = a / n
            shade = shadow / n * SHADOW_ALPHA
            alpha = cover + shade
            if alpha <= 0:
                pixels.append((0, 0))
                continue
            # The shape over its shadow, as one colour and one alpha.
            cr = (r + SHADOW[0] * shade * n) / (a + shade * n)
            cg = (g + SHADOW[1] * shade * n) / (a + shade * n)
            cb = (b + SHADOW[2] * shade * n) / (a + shade * n)
            rgb565 = (int(cr) >> 3) << 11 | (int(cg) >> 2) << 5 | int(cb) >> 3
            pixels.append((min(255, round(alpha * 255)), rgb565))
    return pixels


def main():
    pixels = render()
    lines = [
        "/* Generated by scripts/gen_pass_hand.py. Do not edit. */",
        "#ifndef CTR_PASS_HAND_H",
        "#define CTR_PASS_HAND_H",
        "",
        "/* The Frontier Pass's hand on the top screen, pointing left: row by row,",
        " * each pixel its alpha (0-255) and its colour (RGB565). */",
        f"#define PASS_HAND_W {W}",
        f"#define PASS_HAND_H {H}",
        f"#define PASS_HAND_TIP_X {round(TIP[0] * SCALE)}",
        f"#define PASS_HAND_TIP_Y {round(TIP[1] * SCALE)}",
        "",
        "static const u8 sPassHandAlpha[PASS_HAND_W * PASS_HAND_H] = {",
    ]
    for y in range(H):
        lines.append("    " + ", ".join(f"{p[0]:3d}" for p in pixels[y * W:(y + 1) * W]) + ",")
    lines += ["};", "", "static const u16 sPassHandColour[PASS_HAND_W * PASS_HAND_H] = {"]
    for y in range(H):
        lines.append("    " + ", ".join(f"0x{p[1]:04X}" for p in pixels[y * W:(y + 1) * W]) + ",")
    lines += ["};", "", "#endif", ""]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
