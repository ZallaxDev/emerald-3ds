#!/usr/bin/env python3
"""Local build/deploy pipeline for Project Emerald CTR.

Stages
------
sync      Copy changed files from ``3ds_port/`` (the source of truth) into the
          tree that ``make`` actually builds (``build/upstream/3ds_port``).
dev       Build the full-data 3DSX (romfs backend) and optionally install it.
release   Build the engine-only release 3DSX plus the data pack (``make pak``)
          and optionally install both. No ROM is needed for this path.
payload   Assemble a release ``payload/`` (executable, recipe, voxel
          generators) for the player-facing builder. Needs the vanilla
          pokeemerald ELF; see PIPELINE.md.
builder   Run ``emerald3ds_builder`` against ``dist/payload``.

Examples
--------
    python tools/emerald3ds_pipeline.py sync
    python tools/emerald3ds_pipeline.py dev --deploy
    python tools/emerald3ds_pipeline.py release --deploy
    python tools/emerald3ds_pipeline.py payload --gba-elf /path/pokeemerald.elf
    python tools/emerald3ds_pipeline.py builder --rom ROM --output out

The build runs through devkitPro's msys2 (``C:\\msys64``) because the game's
Makefile needs a POSIX shell, ``make`` and the devkitARM toolchain together.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PORT = REPO / "3ds_port"
TREE = REPO / "build" / "upstream" / "3ds_port"
DEV_TREE = REPO / "build" / "upstream"
DIST = TREE / "dist"
PAYLOAD = DIST / "payload"
AZAHAR_SD = Path(os.environ.get("APPDATA", "")) / "Azahar" / "sdmc"
DEFAULT_GBA_ELF = REPO / "build" / "gba-elf" / "pokeemerald" / "pokeemerald.elf"
BASH = Path(r"C:\msys64\usr\bin\bash.exe")
MSYS_BIN = Path(r"C:\msys64\usr\bin")
MINGW_HINTS = [Path(r"C:\tools\msys64\mingw64\bin"),
               Path(r"C:\Program Files\Git\mingw64\bin")]
PYTHON = sys.executable

# Files a sync never overwrites: they are build outputs, not sources.
SKIP_DIRS = {"build", "dist", "__pycache__"}
SKIP_SUFFIXES = {".o", ".d", ".elf", ".3dsx", ".smdh"}


def posix(path: Path) -> str:
    """A Windows path as the msys2 shell sees it."""
    return path.as_posix()


def msys_path(path: Path) -> str:
    """A Windows path in the form msys2 uses inside a colon-separated PATH
    (/c/...). A drive letter in PATH splits at its own colon, so a Windows
    form entry such as C:/tools/... is read as two broken entries."""
    text = path.as_posix()
    if len(text) > 2 and text[1] == ":":
        return "/" + text[0].lower() + text[2:]
    return text


def log(message: str) -> None:
    print(message, flush=True)


def run(cmd: list[str], cwd: Path | None = None, env: dict | None = None) -> None:
    log("+ " + " ".join(str(c) for c in cmd))
    subprocess.run([str(c) for c in cmd], cwd=cwd, env=env, check=True)


def bash(script: str, cwd: Path = TREE) -> None:
    """Run a shell snippet with make and devkitARM on PATH."""
    if not BASH.exists():
        sys.exit("msys2 bash not found at %s (see PIPELINE.md)." % BASH)
    path = [MSYS_BIN, Path("/opt/devkitpro/devkitARM/bin")]
    path += MINGW_HINTS
    prefix = ":".join(msys_path(p) for p in path)
    # voxel_engine_view.py checks only C:\msys64\mingw64\bin\gcc.exe by default;
    # this machine's host compiler lives elsewhere.
    hostcc = next((p / "gcc.exe" for p in MINGW_HINTS if (p / "gcc.exe").exists()), None)
    env = "export PYTHONUTF8=1; "
    if hostcc:
        env += "export HOSTCC='%s'; " % posix(hostcc)
    command = "%sexport PATH='%s':$PATH; cd '%s' && %s" % (env, prefix, posix(cwd), script)
    run([str(BASH), "-lc", command])


def make(*targets: str, jobs: int = 8) -> None:
    bash("make -j%d %s PYTHON='%s'" % (jobs, " ".join(targets), posix(Path(PYTHON))))


# ---------------------------------------------------------------- sync

def iter_sources() -> list[Path]:
    out = []
    for path in PORT.rglob("*"):
        if not path.is_file():
            continue
        rel = path.relative_to(PORT)
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        if path.suffix in SKIP_SUFFIXES:
            continue
        # romfs/ holds boot.txt and .gitignore in the repo; everything else is
        # generated by the build.
        if rel.parts[0] == "romfs" and rel.name not in ("boot.txt", ".gitignore"):
            continue
        out.append(rel)
    return out


def file_bytes(path: Path) -> bytes:
    """Content with CRLF normalised to LF, so git's autocrlf does not make
    every text file look changed against the tree extracted from the ZIP."""
    data = path.read_bytes()
    if b"\0" in data[:4096]:
        return data
    return data.replace(b"\r\n", b"\n")


def cmd_sync(args) -> int:
    tree = Path(args.tree)
    copied = 0
    for rel in iter_sources():
        src, dst = PORT / rel, tree / rel
        data = file_bytes(src)
        if dst.exists() and dst.read_bytes() == data:
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(data)
        log("sync %s" % rel.as_posix())
        copied += 1
    log("sync: %d file(s) updated, tree=%s" % (copied, tree))
    if copied:
        log("note: the tree is now newer than its object files; make will rebuild what changed.")

    # Apply the script-extension patch to the build tree (upstream root).
    # Sync runs before every build, so this must be idempotent. A half-applied
    # tree is worse than a stopped build: reject files, partial markers and a
    # stale revision all fail loudly instead of being papered over.
    patch_file = REPO / "patches" / "script_extensions.patch"
    if patch_file.exists():
        upstream_root = REPO / "build" / "upstream"
        stamp = upstream_root / ".script_extensions.applied"
        digest = hashlib.sha256(patch_file.read_bytes()).hexdigest()
        rejects = sorted(list((upstream_root / "src").glob("*.rej"))
                         + list((upstream_root / "data").glob("*.rej")))
        if rejects:
            sys.exit("script_extensions.patch: reject files present (%s); restore "
                     "build/upstream before rebuilding"
                     % ", ".join(str(p.relative_to(upstream_root)) for p in rejects))

        markers = {
            "src/script.c": "ScriptExt_DispatchCommand",
            "src/scrcmd.c": "ScriptExt_IsSpecialRegistered",
            "src/battle_setup.c": "BATTLE_HOOK_PRE_WILD",
            "src/field_control_avatar.c": "FrameCallback_RunAll",
            "data/event_scripts.s": "gUpstreamSpecialCount",
        }
        applied = [
            rel for rel, marker in markers.items()
            if (upstream_root / rel).exists()
            and marker in (upstream_root / rel).read_text(errors="ignore")
        ]
        if len(applied) == len(markers):
            if stamp.exists() and stamp.read_text(encoding="utf-8").strip() == digest:
                log("script_extensions.patch: already applied")
            else:
                sys.exit("script_extensions.patch: the tree has the patch but not this "
                         "revision; reverse the old patch or re-bootstrap before syncing")
        elif applied:
            sys.exit(
                "script_extensions.patch: partially applied (%s); restore "
                "build/upstream from a clean tree before rebuilding"
                % ", ".join(applied))
        else:
            log("applying script_extensions.patch...")
            apply_cmd = "patch -p1 --dry-run -f -i '%s' && patch -p1 -f -i '%s'"
            apply_cmd %= (posix(patch_file), posix(patch_file))
            bash(apply_cmd, cwd=upstream_root)
            stamp.write_text(digest + "\n", encoding="utf-8")
            log("script_extensions.patch: applied")

    return 0


# ---------------------------------------------------------------- build

def cmd_dev(args) -> int:
    cmd_sync(args)
    make()
    artifact = TREE / "emerald3ds.3dsx"
    if not artifact.exists():
        sys.exit("build did not produce %s" % artifact)
    log("dev: %s (%.1f MiB)" % (artifact, artifact.stat().st_size / 1048576))
    if args.deploy:
        deploy([(artifact, "emerald3ds.3dsx")], args)
    return 0


def cmd_release(args) -> int:
    cmd_sync(args)
    make("release")
    make("pak")
    exe = DIST / "Emerald3DS.3dsx"
    pak = TREE / "build" / "emerald3ds.pak"
    for path in (exe, pak):
        if not path.exists():
            sys.exit("release did not produce %s" % path)
    log("release: %s (%.1f MiB)" % (exe, exe.stat().st_size / 1048576))
    log("release: %s (%.1f MiB)" % (pak, pak.stat().st_size / 1048576))
    if args.deploy:
        deploy([(exe, "emerald3ds.3dsx"), (pak, "emerald3ds.pak")], args)
    return 0


# ---------------------------------------------------------------- payload

PAYLOAD_FILES = ["Emerald3DS.3dsx", "Emerald3DS.smdh"]
VOXELGEN_EXTRA = ["src/voxel/voxel_regions.h", "assets/voxel/relief_fixes.json"]


def cmd_payload(args) -> int:
    gba_elf = Path(args.gba_elf) if args.gba_elf else (
        DEFAULT_GBA_ELF if DEFAULT_GBA_ELF.exists() else None)
    recipe = Path(args.recipe) if args.recipe else DIST / "emerald3ds.recipe"
    if not recipe.exists() and (gba_elf is None or not args.rom):
        log("payload: a recipe needs both --gba-elf and --rom.\n"
            "\n"
            "Looked for the vanilla ELF at:\n  %s\n"
            "The builder's recipe maps every data file back to the vanilla ROM.\n"
            "Its voxel section needs the symbol offsets of the ORIGINAL game's ELF\n"
            "(pokeemerald, unpatched, built with the pinned agbcc).\n"
            "\n"
            "See PIPELINE.md (project root), section 'Player-facing builder'. Until then use\n"
            "  python tools/emerald3ds_pipeline.py release --deploy\n"
            "which produces the same data pack with 'make pak'." % DEFAULT_GBA_ELF)
        return 2
    cmd_sync(args)
    if not recipe.exists():
        make("release")
        bash("'%s' ../tools/gen_recipe.py --romfs romfs --rom '%s' --out '%s' "
             "--release %s --elf emerald3ds.elf --gba-elf '%s' "
             "--image-elf build/gamedata_image.elf --image-map build/gamedata_image.map"
             % (posix(Path(PYTHON)), posix(Path(args.rom)), posix(recipe),
                args.version, posix(gba_elf)))
        bash("'%s' ../tools/voxel_precompile.py --recipe '%s' --rom '%s' --port ."
             % (posix(Path(PYTHON)), posix(recipe), posix(Path(args.rom))))
    make("release")
    if PAYLOAD.exists():
        shutil.rmtree(PAYLOAD)
    PAYLOAD.mkdir(parents=True)
    for name in PAYLOAD_FILES:
        shutil.copy2(DIST / name, PAYLOAD / name)
    shutil.copy2(recipe, PAYLOAD / "emerald3ds.recipe")
    scripts = PORT / "scripts"
    (PAYLOAD / "voxelgen" / "scripts").mkdir(parents=True, exist_ok=True)
    for path in sorted(scripts.glob("*.py")):
        shutil.copy2(path, PAYLOAD / "voxelgen" / "scripts" / path.name)
    for rel in VOXELGEN_EXTRA:
        dst = PAYLOAD / "voxelgen" / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(PORT / rel, dst)
    log("payload: %s" % PAYLOAD)
    return 0


def cmd_builder(args) -> int:
    if not (PAYLOAD / "emerald3ds.recipe").is_file():
        sys.exit("no payload recipe at %s: run 'payload' first." % PAYLOAD)
    run([PYTHON, "-m", "emerald3ds_builder", "--payload", str(PAYLOAD),
         "build", "--rom", str(args.rom), "--output", str(args.output)],
        cwd=REPO / "builder")
    return 0


# ---------------------------------------------------------------- deploy

def deploy(items, args) -> None:
    root = Path(args.sd) if args.sd else AZAHAR_SD
    dest = root / "3ds" / "emerald3ds"
    dest.mkdir(parents=True, exist_ok=True)
    for src, name in items:
        shutil.copy2(src, dest / name)
        log("deploy: %s -> %s" % (src.name, dest / name))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tree", default=str(TREE), help="the build tree (default: %(default)s)")
    sub = ap.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("sync", help="copy changed 3ds_port files into the build tree")
    s.set_defaults(func=cmd_sync)

    d = sub.add_parser("dev", help="build the full-data 3DSX")
    d.add_argument("--deploy", action="store_true")
    d.add_argument("--sd", help="SD/sdmc root (default: Azahar)")
    d.set_defaults(func=cmd_dev)

    r = sub.add_parser("release", help="build the engine-only 3DSX and the data pack")
    r.add_argument("--deploy", action="store_true")
    r.add_argument("--sd", help="SD/sdmc root (default: Azahar)")
    r.set_defaults(func=cmd_release)

    p = sub.add_parser("payload", help="assemble a builder payload")
    p.add_argument("--rom", help="kept for symmetry; the recipe step also needs the ROM")
    p.add_argument("--gba-elf", help="vanilla pokeemerald ELF (needed to make a recipe)")
    p.add_argument("--recipe", help="reuse an existing emerald3ds.recipe")
    p.add_argument("--version", default="0.5.0")
    p.set_defaults(func=cmd_payload)

    b = sub.add_parser("builder", help="run the player-facing builder")
    b.add_argument("--rom", required=True)
    b.add_argument("--output", required=True)
    b.set_defaults(func=cmd_builder)

    args = ap.parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())